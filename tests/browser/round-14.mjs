const task=await taskSpace(4);const page=task.page('p1');const fs=await import('node:fs/promises');
const root='C:/Users/artho/Documents/Projetos AI/arthonjunieres.site/docs/evidence';
await page.click('loc=role:button[name="Reproduzir animação"]');
await page.waitForFunction(()=>window.ArthonSwarm.active);
const native=await page.evaluate(()=>({active:window.ArthonSwarm.active,reduced:matchMedia('(prefers-reduced-motion: reduce)').matches,url:location.href}));
await page.screenshot({path:root+'/fixed-native-motion.png'});
await page.keyboard.press('Escape');
const stopped=await page.evaluate(()=>!window.ArthonSwarm.active);
await page.cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
await page.cdp('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});
await page.goto('http://127.0.0.1:8080/');
await page.waitForFunction(()=>window.ArthonSwarm.active);
const automatic=await page.evaluate(()=>({active:window.ArthonSwarm.active,url:location.href}));
await page.screenshot({path:root+'/fixed-desktop.png'});
await page.cdp('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:false});
await page.goto('http://127.0.0.1:8080/');
await page.waitForFunction(()=>window.ArthonSwarm.active);
await page.screenshot({path:root+'/fixed-mobile.png'});
const mobile=await page.evaluate(()=>({active:window.ArthonSwarm.active,overflow:document.documentElement.scrollWidth>innerWidth}));
await page.goto('http://127.0.0.1:8080/?swarm=0');
const disabled=await page.evaluate(()=>!window.ArthonSwarm.active);
console.log({native,stopped,automatic,mobile,disabled});
await fs.writeFile(root+'/fix-browser-results.json',JSON.stringify({native,stopped,automatic,mobile,disabled},null,2));
console.log(await page.snapshot());
await task.finish({keep:[]});
